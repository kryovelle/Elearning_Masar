window.translations = translations;

function handleRTL(lang) {
    const isRTL = lang === 'ar';

    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    document.body.classList.toggle('rtl', isRTL);

    const heroContent = document.querySelector('.hero-content');
    const heroImage = document.querySelector('.hero-image');

    if (heroContent && heroImage) {
        heroImage.style.order = isRTL ? '0' : '1';
        heroContent.style.order = isRTL ? '1' : '0';
        heroContent.style.textAlign = isRTL ? 'right' : 'left';
    }

    // ... your step-item / course-card / why-item / testimonial code stays the same
}

window.applyLanguage = function(lang) {
    const dict = translations[lang];
    if (!dict) return;

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // Update language switcher buttons for PUBLIC pages (.language-switcher)
    document.querySelectorAll('.language-switcher button').forEach(btn => {
        btn.style.fontWeight = btn.textContent.toLowerCase() === lang ? 'bold' : 'normal';
    });

    // Update language switcher buttons for STUDENT pages (.lang-btn)
    document.querySelectorAll('.lang-btn').forEach(btn => {
        // Remove active class from all buttons
        btn.classList.remove('active');
        
        // Get the language from data-lang attribute or button text
        const btnLang = btn.getAttribute('data-lang') || btn.textContent.toLowerCase();
        
        // Add active class to the current language button
        if (btnLang === lang) {
            btn.classList.add('active');
        }
    });

    // Handle RTL/LTR
    handleRTL(lang);
};

window.switchLanguage = function(lang) {
    localStorage.setItem('preferred_language', lang);
    window.applyLanguage(lang); // applyLanguage already calls handleRTL
    if (typeof window.loadHomeData === 'function') {
        window.loadHomeData();
    }
};

document.addEventListener('DOMContentLoaded', function() {
    const preferredLang = localStorage.getItem('preferred_language') ||
                          document.documentElement.lang || 'en';
    window.switchLanguage(preferredLang);
});